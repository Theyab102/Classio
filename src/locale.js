let interfacePreference = 'auto';
try { const saved = localStorage.getItem('classio_interface_language'); if (['auto','en','ar'].includes(saved)) interfacePreference = saved; } catch {}
let replyPreference = 'auto';
try { const saved=localStorage.getItem('classio_lang'); if(replyLanguages.includes(saved))replyPreference=saved; } catch {}
const listeners = new Set();
function resolvedLocale() { return interfacePreference === 'auto' ? (navigator.language?.startsWith('ar') ? 'ar' : 'en') : interfacePreference; }
export function translate(text) { return resolvedLocale() === 'ar' ? ar[text] || text : text; }
export function getReplyLanguage() { return replyPreference; }
export function getLanguagePreferences() { return { interfaceLanguage: interfacePreference, replyLanguage: getReplyLanguage() }; }
function apply() {
  const locale = resolvedLocale();
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  listeners.forEach(listener => listener());
}
export function setLanguages(next, { remote = false } = {}) {
  if (['auto','en','ar'].includes(next.interfaceLanguage)) interfacePreference = next.interfaceLanguage;
  if(replyLanguages.includes(next.replyLanguage)) replyPreference=next.replyLanguage;
  try {
    localStorage.setItem('classio_interface_language', interfacePreference);
    if (replyLanguages.includes(next.replyLanguage)) localStorage.setItem('classio_lang', next.replyLanguage);
  } catch {}
  apply();
  if (!remote) window.dispatchEvent(new CustomEvent('classio-language-change', { detail: getLanguagePreferences() }));
}
export function useLocale() {
  useSyncExternalStore(listener => { listeners.add(listener); return () => listeners.delete(listener); }, () => interfacePreference + '|' + replyPreference + '|' + resolvedLocale());
  return { locale:resolvedLocale(), t: translate, direction: resolvedLocale() === 'ar' ? 'rtl' : 'ltr' };
}
if (typeof document !== 'undefined') apply();
window.addEventListener('languagechange', apply);
window.addEventListener('storage', event => {
  if (event.key === 'classio_interface_language' || event.key === 'classio_lang') {
    if (event.key === 'classio_interface_language') interfacePreference = ['auto','en','ar'].includes(event.newValue) ? event.newValue : 'auto';
    if(event.key==='classio_lang') replyPreference=replyLanguages.includes(event.newValue)?event.newValue:'auto';
    apply();
  }
});
